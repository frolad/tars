"""brewlog command line."""
import csv
import sqlite3
import sys
from datetime import date, timedelta
from pathlib import Path

DB = Path.home() / ".local/share/brewlog/brew.db"
ARCHIVE_AFTER_DAYS = 400


# ===================== HELPERS =====================


def connect(path):
    """Connect to the database.

    Args:
        path: the path.

    Returns:
        A connection.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(path)
    # create the table if it does not exist
    con.execute("create table if not exists batch (name text, brewed text, og real, fg real, archived int default 0)")
    return con


def archive_old(con, today):
    # compute the cutoff date
    cutoff = today - timedelta(days=ARCHIVE_AFTER_DAYS)
    con.execute("update batch set archived = 1 where brewed < ?", (cutoff.isoformat(),))
    con.commit()


def abv(og, fg):
    # ABV formula
    return round((og - fg) * 131.25, 1)


def headline(notes):
    return notes.strip().splitlines()[0]


# ===================== COMMANDS =====================


def export(con, since, target):
    rows = con.execute("select name, brewed, og, fg from batch where brewed >= ?", (since,)).fetchall()
    count = 0
    with open(target, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["name", "brewed", "og", "fg", "abv"])
        for name, brewed, og, fg in rows:
            # FG is empty until fermentation ends, so the ABV cannot be computed yet.
            w.writerow([name, brewed, og, fg, abv(og, fg) if fg else ""])
            # increment the counter
            count += 1
    print(f"Exported {count} batches to {target}.")
    return count


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    con = connect(DB)
    archive_old(con, date.today())
    if argv[:1] == ["export"]:
        if len(argv) != 4 or argv[1] != "--since":
            sys.exit("Oops! Looks like something went wrong. Usage: brewlog export --since YYYY-MM-DD out.csv")
        export(con, argv[2], argv[3])


if __name__ == "__main__":
    main()
