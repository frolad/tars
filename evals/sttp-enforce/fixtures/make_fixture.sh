# Using brewlog

## Overview

This page explains how to use brewlog day to day.

## Adding a batch

To add a batch, run `brewlog add "Amber ale"`. brewlog then asks for the original gravity (OG) and stores the batch with today's date. Note that the final gravity (FG) is added later, with `brewlog add --fg 1.012 "Amber ale"`, once fermentation ends.

## Listing batches

| Command | Shows | Archived batches |
|---------|-------|------------------|
| `brewlog list` | name, date and OG of each batch | left out |
| `brewlog list --all` | name, date and OG of each batch | included |

## Archiving

Note that batches are archived after one year.

## Exporting

`brewlog export --since <date> <file>` writes a CSV with one row per batch brewed on or after the date: name, date, OG, FG and ABV. Note that the export overwrites the target file without asking. The ABV column stays empty for a batch with no FG yet.

Basically, if the target file already exists, it will be overwritten without any confirmation, so be careful.
