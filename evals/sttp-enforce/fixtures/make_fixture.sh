import csv
import tempfile
import unittest
from datetime import date
from pathlib import Path

from brewlog.cli import abv, archive_old, connect, export, headline


class CliTest(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.con = connect(self.tmp / "brew.db")

    def test_abv(self):
        self.assertEqual(abv(1.060, 1.012), 6.3)

    def test_export_writes_one_row_per_batch(self):
        self.con.executemany("insert into batch (name, brewed, og, fg) values (?, ?, ?, ?)",
                             [("Amber ale", "2025-02-01", 1.060, 1.012), ("Stout", "2025-03-01", 1.070, None)])
        self.assertEqual(export(self.con, "2025-01-01", self.tmp / "out.csv"), 2)
        rows = list(csv.reader(open(self.tmp / "out.csv")))
        self.assertEqual(rows[0], ["name", "brewed", "og", "fg", "abv"])
        self.assertEqual(rows[2][4], "")

    def test_archive_after_400_days(self):
        self.con.executemany("insert into batch (name, brewed) values (?, ?)", [("old", "2024-08-01"), ("new", "2024-09-10")])
        archive_old(self.con, date(2025, 9, 9))
        self.assertEqual(dict(self.con.execute("select name, archived from batch")), {"old": 1, "new": 0})

    def test_headline_is_the_first_line_of_the_notes(self):
        notes = (Path(__file__).parent / "fixtures/notes.md").read_text()
        self.assertEqual(headline(notes), "Honestly, I think this batch basically turned out really, really well!")
