# Releasing brewlog 🚀

## Introduction

This skill explains how to release brewlog. Releasing is a really important part of our workflow, and we want every release to be of the highest quality, because quality matters to us and to our users.

## Before you start

First of all, it's worth noting that you should always run the full test suite with `python3 -m unittest` before doing anything else. Never tag a release on a red build. Remember that tests are really important!

## Steps

1. **Check the changelog.** Open `CHANGELOG.md` and look at the `Unreleased` section. If it has no entries, stop and ask the user what changed; do not invent entries.
2. **Bump the version.** The version lives in `pyproject.toml`. Bump it with `bump-my-version bump patch` for a fix, or `bump-my-version bump minor` for a feature. Please do not edit the version by hand.
3. **Tag.** Create the tag in the format `v<major>.<minor>.<patch>`, for example `v1.4.2`.
4. **Push.** Before pushing the tag, ask the user. Pushing the tag starts the publish workflow, which uploads the release to PyPI.

## Important notes

| Note |
|------|
| Always ask the user before pushing the tag. |
| PyPI rejects a second upload of the same version, so a wrong tag cannot be fixed by pushing it again: the fix is a new patch version. |
| Do not push without asking the user first. |

## Summary

In summary, run the tests, check the changelog, bump the version, tag, and then ask the user before you push. That's it! 🎉
