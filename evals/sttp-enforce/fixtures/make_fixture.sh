# brewlog 🍺

Welcome to brewlog! In this document we will walk you through everything you need to know to get started. We hope you enjoy using it as much as we enjoyed building it.

## Introduction

brewlog is a really simple, lightweight command-line tool that keeps a log of your homebrew batches: what went into each batch, its gravity readings and its tasting notes.

## Installation

It's worth noting that brewlog needs **Python 3.11** or newer. To install it, simply run the following command from the root of the checkout:

    pip install -e .

## Configuration

Generally speaking, you probably won't need to change anything. That said, the configuration lives in `~/.config/brewlog/config.toml`, and the database is a SQLite file at `~/.local/share/brewlog/brew.db`.

## Archiving

Batches older than 400 days are archived automatically the next time brewlog starts. Archived batches stay in the database but no longer show up in `brewlog list`.

## Exporting

You can export your batches to CSV with `brewlog export --since 2025-01-01 out.csv`. ⚠️ **Important:** please be aware that the export overwrites the target file without asking, so make sure you don't point it at a file you want to keep!

## Commands

| Command |
|---------|
| `brewlog add` |
| `brewlog list` |
| `brewlog export` |

## Contributing

Contributions are always welcome! Run the tests with `python3 -m unittest` before opening a pull request.

In summary, brewlog keeps your brewing organised. Happy brewing! 🍻
